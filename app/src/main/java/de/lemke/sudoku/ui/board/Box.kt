package de.lemke.sudoku.ui.board

data class Box(
    val left: Float,
    val top: Float,
    val right: Float,
    val bottom: Float,
) {
    val width: Float get() = right - left
    val height: Float get() = bottom - top
    val centerX: Float get() = (left + right) / 2
    val centerY: Float get() = (top + bottom) / 2

    fun inset(
        left: Float,
        top: Float,
        right: Float,
        bottom: Float,
    ): Box = Box(this.left + left, this.top + top, this.right - right, this.bottom - bottom)
}
